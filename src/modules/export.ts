import { createHash } from "node:crypto"
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import type { Claim } from "../claims"
import type { HarnessContext } from "../context"
import type { TopicConfig } from "../topic-config"

const MAX_EVIDENCE = 50
const MAX_LOCATOR = 512
const CONFIDENCE = { verified: "high", likely: "medium", speculative: "low" } as const

/** Go's %q for the strings we write (ASCII-safe JSON quoting matches it for these values). */
function q(s: string): string {
  return JSON.stringify(s)
}

function atomicWrite(path: string, body: string): void {
  const tmp = `${path}.tmp-${process.pid}`
  writeFileSync(tmp, body)
  renameSync(tmp, path)
}

/** `owner/repo@sha` from the first evidence locator that carries a repo pin. */
export function asOfFor(claim: Claim): string | null {
  for (const e of claim.evidence) {
    const m = /^([\w.-]+\/[\w.-]+)@([0-9a-f]{7,40})\b/.exec(e.locator.trim())
    if (m) return `${m[1]}@${m[2]}`
  }
  return null
}

export function evidenceFor(slug: string, claim: Claim): string[] {
  const own = `research:${slug}/claim:${claim.id}`
  const locs = [...new Set(claim.evidence.map((e) => e.locator.trim()).filter(Boolean))]
    .map((l) => l.slice(0, MAX_LOCATOR))
    .slice(0, MAX_EVIDENCE - 1)
  return [...locs, own]
}

function validityFor(claim: Claim): "current" | "historical" | null {
  if (claim.status === "verified") return "current"
  if (claim.status === "refuted" && claim.deweyIdentity) return "historical"
  return null
}

export function exportHash(slug: string, claim: Claim): string {
  const fields = {
    slug,
    layer: claim.layer,
    assertion: claim.assertion,
    mechanism: claim.mechanism,
    failureMode: claim.failureMode,
    status: claim.status,
    confidence: claim.confidence,
    confidenceBasis: claim.confidenceBasis,
    category: claim.category,
    evidence: claim.evidence,
  }
  return createHash("sha256").update(JSON.stringify(fields)).digest("hex").slice(0, 16)
}

function stamp(d: Date): string {
  return d.toISOString().replace(/[-:]/g, "").replace(/\.\d+Z$/, "")
}

function body(slug: string, claim: Claim): string {
  const lines = [
    `# ${claim.id}: ${claim.assertion}`,
    "",
    `**Mechanism:** ${claim.mechanism}`,
  ]
  if (claim.failureMode) lines.push("", `**Failure mode:** ${claim.failureMode}`)
  lines.push(
    "",
    `**Topic:** ${slug} · **Layer:** ${claim.layer} · **Status:** ${claim.status} · **Confidence:** ${claim.confidence}`,
    "",
    `**What would change it:** ${claim.confidenceBasis}`,
    "",
    "**Evidence:**",
    ...claim.evidence.map((e) => `- ${e.relation}: ${e.locator} (${e.source}) — ${e.observation}`),
  )
  return lines.join("\n")
}

/**
 * The learning file, in the field order Dewey's `writeLearningFile` uses
 * (tag, author, category, created_at, identity, tier, then the temporal
 * fields as_of / evidence / validity / supersedes). `confidence` follows
 * `tier`; Dewey keeps unknown keys as page properties.
 */
export function renderLearning(opts: {
  slug: string
  author: string
  identity: string
  createdAt: Date
  claim: Claim
  validity: string
  supersedes: string | null
}): string {
  const { claim } = opts
  const fm = [
    "---",
    `tag: ${opts.slug}`,
    `author: ${opts.author}`,
    `category: ${claim.category}`,
    `created_at: ${opts.createdAt.toISOString().replace(/\.\d+Z$/, "Z")}`,
    `identity: ${opts.identity}`,
    "tier: draft",
    `confidence: ${CONFIDENCE[claim.confidence]}`,
  ]
  const asOf = asOfFor(claim)
  if (asOf) fm.push(`as_of: ${q(asOf)}`)
  fm.push("evidence:", ...evidenceFor(opts.slug, claim).map((e) => `  - ${q(e)}`))
  fm.push(`validity: ${q(opts.validity)}`)
  if (opts.supersedes) fm.push(`supersedes: ${q(opts.supersedes)}`)
  fm.push("---", "")
  return `${fm.join("\n")}\n${body(opts.slug, claim)}\n`
}

/** Marks an earlier learning superseded, as Dewey's supersession does. */
function markSuperseded(path: string, successor: string): void {
  if (!existsSync(path)) return
  const text = readFileSync(path, "utf8")
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text)
  if (!m) return
  const kept = m[1]!.split("\n").filter((l) => !/^(validity|superseded_by):/.test(l))
  kept.push(`validity: ${q("superseded")}`, `superseded_by: ${q(successor)}`)
  atomicWrite(path, `---\n${kept.join("\n")}\n---\n${text.slice(m[0].length)}`)
}

function claimsMarkdown(topic: TopicConfig, claims: Claim[]): string {
  const order = ["verified", "hypothesis", "out-of-scope", "refuted"] as const
  const out = [
    `# Claims — ${topic.title}`,
    "",
    "Generated by opencode-research-harness from `claims.jsonl`. Do not edit here; use the ledger tools.",
    "",
  ]
  for (const status of order) {
    const group = claims.filter((c) => c.status === status)
    if (!group.length) continue
    out.push(`## ${status[0]!.toUpperCase()}${status.slice(1)} (${group.length})`, "")
    for (const c of group) {
      out.push(`### ${c.id}`, "", `${c.assertion}`, "")
      out.push(`- **Layer:** ${c.layer} · **Confidence:** ${c.confidence} — ${c.confidenceBasis}`)
      out.push(`- **Mechanism:** ${c.mechanism}`)
      if (c.failureMode) out.push(`- **Failure mode:** ${c.failureMode}`)
      for (const e of c.evidence) out.push(`- **Evidence (${e.relation}):** ${e.locator} — ${e.observation}`)
      if (c.deweyIdentity) out.push(`- **Dewey:** learning/${c.deweyIdentity}`)
      out.push("")
    }
  }
  if (claims.length === 0) out.push("No claims yet.", "")
  return out.join("\n")
}

export interface ExportReport {
  exported: { id: string; identity: string; validity: string; supersedes: string | null }[]
  unchanged: string[]
  skipped: string[]
}

/** FR-E1..E3: verified (and newly refuted) claims → Dewey learnings; regenerate CLAIMS.md. */
export function exportTopic(ctx: HarnessContext, sessionId: string, topic: TopicConfig, now = new Date()): ExportReport {
  const slug = topic.slug
  const dir = join(ctx.directory, ctx.config.dewey.learningsDir)
  mkdirSync(dir, { recursive: true })
  const report: ExportReport = { exported: [], unchanged: [], skipped: [] }
  const updated: Claim[] = []

  for (const claim of ctx.db.claims(slug)) {
    const validity = validityFor(claim)
    if (!validity) {
      report.skipped.push(claim.id)
      continue
    }
    const hash = exportHash(slug, claim)
    if (hash === claim.exportedHash) {
      report.unchanged.push(claim.id)
      continue
    }
    const base = `${slug}-${stamp(now)}-${ctx.config.author}`
    let identity = base
    for (let n = 2; existsSync(join(dir, `${identity}.md`)); n++) identity = `${base}-${n}`
    const supersedes = claim.deweyIdentity
    writeFileSync(
      join(dir, `${identity}.md`),
      renderLearning({ slug, author: ctx.config.author, identity, createdAt: now, claim, validity, supersedes }),
    )
    if (supersedes) markSuperseded(join(dir, `${supersedes}.md`), identity)
    updated.push({ ...claim, deweyIdentity: identity, exportedHash: hash })
    report.exported.push({ id: claim.id, identity, validity, supersedes })
  }

  if (updated.length) ctx.db.saveClaims(slug, sessionId, "export", updated)
  atomicWrite(join(ctx.directory, ctx.config.topicsDir, slug, "CLAIMS.md"), claimsMarkdown(topic, ctx.db.claims(slug)))
  return report
}

export function exportReportText(topic: TopicConfig, r: ExportReport, learningsDir: string): string {
  const lines = [`Exported topic \`${topic.slug}\` to ${learningsDir}/ and regenerated topics/${topic.slug}/CLAIMS.md.`]
  if (r.exported.length) {
    lines.push("", "Written:")
    for (const e of r.exported) {
      lines.push(`- ${e.id} → learning/${e.identity} (${e.validity}${e.supersedes ? `, supersedes ${e.supersedes}` : ""})`)
    }
    lines.push(
      "",
      "Dewey re-reads changed learning files when it starts, so these become searchable after the next Dewey server start or `dewey reindex`.",
    )
  } else {
    lines.push("", "Nothing new to export.")
  }
  if (r.unchanged.length) lines.push(`Unchanged since last export: ${r.unchanged.join(", ")}`)
  if (r.skipped.length) lines.push(`Not exported (not verified): ${r.skipped.join(", ")}`)
  return lines.join("\n")
}
